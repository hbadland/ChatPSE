def _levenshtein(a: str, b: str) -> int:
    """Edit distance between two strings (pure Python, O(len(a)*len(b)))."""
    if len(a) < len(b):
        a, b = b, a
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a):
        curr = [i + 1]
        for j, cb in enumerate(b):
            curr.append(min(prev[j + 1] + 1, curr[j] + 1,
                            prev[j] + (ca != cb)))
        prev = curr
    return prev[-1]


# ── Database parsing ───────────────────────────────────────────────────────────

def _parse_database(
        md: str,
) -> tuple[dict, dict, dict, dict, set]:
    """
    Parse compound_database.md into five structures.

    Returns
    -------
    lookup        : {alias_lower → dwsim_name}
    mixtures      : {alias_lower → [dwsim_names]}
    mixture_fracs : {alias_lower → {dwsim_name → mole_fraction}}
    unsupported   : {keyword_lower → reason}   (formal AND colloquial names)
    unverified    : {dwsim_name}               (? status — warn at runtime)
    """
    lookup:        dict[str, str]             = {}
    mixtures:      dict[str, list[str]]       = {}
    mixture_fracs: dict[str, dict[str, float]] = {}
    unsupported:   dict[str, str]             = {}
    unverified:    set[str]                   = set()

    section = None
    for line in md.splitlines():
        line = line.strip()

        if "Single-Component Aliases" in line:
            section = "single";     continue
        if "Multi-Component Mixture" in line:
            section = "mixture";    continue
        if "Unsupported Compounds" in line:
            section = "unsupported"; continue
        if line.startswith("## ") or line.startswith("# "):
            section = None;         continue

        if not line.startswith("|") or line.startswith("| ---") or line.startswith("|---"):
            continue
        cols = [c.strip() for c in line.split("|") if c.strip()]
        if not cols:
            continue

        # ── Single-component ──────────────────────────────────────────────────
        if section == "single" and len(cols) >= 3:
            dwsim_name  = cols[0]
            cas_raw     = cols[1].strip()
            aliases_raw = cols[2]               # col 1 = CAS
            verified    = cols[4].strip() if len(cols) >= 5 else "?"
            # Split on ", " (comma+space) to preserve names like N,N-dimethylformamide
            aliases = [a.strip() for a in aliases_raw.split(", ") if len(a.strip()) >= 3]
            lookup[dwsim_name.lower()] = dwsim_name
            # CAS number as a direct lookup key (e.g. "7732-18-5" → "Water")
            if _CAS_RE.match(cas_raw):
                lookup[cas_raw] = dwsim_name
            for alias in aliases:
                lookup[alias.lower()] = dwsim_name
            if "?" in verified:
                unverified.add(dwsim_name)

        # ── Multi-component mixture ───────────────────────────────────────────
        elif section == "mixture" and len(cols) >= 2:
            alias_raw    = cols[0]
            alias_lower  = alias_raw.lower()
            components   = [c.strip() for c in cols[1].split(",") if c.strip()]
            mixtures[alias_lower] = components
            for word in alias_lower.split():
                if len(word) > 3:
                    mixtures.setdefault(word, components)

            # Parse optional mole-fraction column (col index 2)
            if len(cols) >= 3:
                frac_raw = cols[2]
                try:
                    fracs = [float(f.strip()) for f in frac_raw.split(",") if f.strip()]
                    if len(fracs) == len(components):
                        mixture_fracs[alias_lower] = dict(zip(components, fracs))
                except ValueError:
                    pass  # Non-numeric cell (e.g. header row)

        # ── Unsupported ───────────────────────────────────────────────────────
        elif section == "unsupported" and len(cols) >= 4:
            # 4-column format: Compound/Class | Colloquial Names | Category | Reason
            formal_names      = cols[0]
            colloquial_names  = cols[1]
            reason            = cols[3]
            # Register all formal names (comma-separated within the cell)
            for name in formal_names.split(","):
                name = name.strip()
                if name:
                    unsupported[name.lower()] = reason
            # Register all colloquial names
            for name in colloquial_names.split(","):
                name = name.strip()
                if name and len(name) >= 3:
                    unsupported[name.lower()] = reason

    return lookup, mixtures, mixture_fracs, unsupported, unverified


