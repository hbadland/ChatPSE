"""
Basis Agent: compound name normalisation for DWSIM.

Converts user-supplied chemical names (trivial names, abbreviations, trade names,
mixture aliases) into exact DWSIM compound names before the Planner runs.

Two-stage design
────────────────
Stage 1 — Deterministic lookup (zero LLM cost):
    Parses compound_database.md at import time into four structures:
      _LOOKUP       : {alias_lower → dwsim_name}
      _MIXTURES     : {alias_lower → [dwsim_names]}
      _MIXTURE_FRACS: {alias_lower → {dwsim_name → mole_fraction}}
      _UNSUPPORTED  : {keyword_lower → reason}   (formal + colloquial names)
    Scans description for known aliases using word-boundary regex (no substrings).
    Results become *anchors* — candidate compounds passed to Stage 2 for verification.

Stage 2 — LLM verifier-completer (always runs):
    Receives the process description plus Stage 1 anchors.
    Three tasks:
      (a) Verify anchors — reject false positives (e.g. "He" matched Helium in prose).
      (b) Complete — find compounds Stage 1 missed (IUPAC names, novel trade names).
      (c) Extract concentration hints and mixture compositions from context.
    Output: confirmed DWSIM names + warnings/errors for unsupported / unverified.

Stage 2 fallback:
    If the LLM call fails (network error, rate limit, quota exhausted), the agent
    falls back to Stage 1 anchors with a WARNING — never silently drops compounds.

Knowledge base:
    context/compound_database.md — single source of truth.
    Add compounds there; no Python changes required.
    Parsed on every BasisAgent instantiation so .md edits take effect immediately.

BasisResult fields:
    compound_map          : {original_text → dwsim_name or [dwsim_names]}
    dwsim_compounds       : flat de-duplicated list of DWSIM names
    normalised_description: description with mentions replaced by DWSIM names
    suggested_compositions: {mixture_alias → {dwsim_name → mole_fraction}}
    concentration_hints   : textual hints about concentrations / compositions
    warnings              : non-fatal issues (unverified names, mixture expansions)
    errors                : fatal issues (unsupported compounds found)
    success               : False when errors is non-empty
    stage                 : "LOOKUP" | "LLM" | "PARTIAL"  (PARTIAL = LLM fallback)
    stage1_count          : number of anchors supplied by Stage 1
"""
