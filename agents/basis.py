# ── Result type ────────────────────────────────────────────────────────────────

@dataclass
class BasisResult:
    compound_map:           dict[str, str | list[str]]   # original text → dwsim name(s)
    dwsim_compounds:        list[str]                    # flat unique DWSIM list
    normalised_description: str
    # Key = original user text (e.g. "natural gas"), value = {dwsim_name: mole_fraction}.
    # Downstream agents should iterate dwsim_compounds for the compound list and use
    # this dict only to initialise feed compositions.
    suggested_compositions: dict[str, dict[str, float]] = field(default_factory=dict)
    concentration_hints:    list[str]                   = field(default_factory=list)
    warnings:               list[str]                   = field(default_factory=list)
    errors:                 list[str]                   = field(default_factory=list)
    stage:                  str  = "LOOKUP"             # LOOKUP | LLM | PARTIAL
    stage1_count:           int  = 0
    success:                bool = True

    def summary(self) -> str:
        lines = [
            f"Stage: {self.stage}   Success: {self.success}   "
            f"Stage1 anchors: {self.stage1_count}",
            f"DWSIM compounds: {self.dwsim_compounds}",
        ]
        for orig, dwsim in self.compound_map.items():
            lines.append(f"  {orig!r:30s} → {dwsim}")
        if self.suggested_compositions:
            lines.append("Suggested compositions:")
            for alias, comp in self.suggested_compositions.items():
                lines.append(f"  {alias}: {comp}")
        if self.concentration_hints:
            lines.append("Concentration hints:")
            lines.extend(f"  {h}" for h in self.concentration_hints)
        if self.warnings:
            lines.append("Warnings:")
            lines.extend(f"  ⚠ {w}" for w in self.warnings)
        if self.errors:
            lines.append("Errors:")
            lines.extend(f"  ✗ {e}" for e in self.errors)
        return "\n".join(lines)


